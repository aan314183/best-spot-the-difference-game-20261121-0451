/* Lantern Lane — scene data.
   Every scene is one list of drawable elements plus ten differences.
   The left panel draws the list as-is; the right panel draws the same
   list with the differences applied (render.js). No copied art: all
   shapes, names and scenes are invented for this game.
   Element kinds: rect, circle, ellipse, poly, path, text, line.
   A difference: { id, x, y, r, label, kind, ... } where kind is one of
   remove | recolor | move | add | retext, applied to the element whose
   id it names (add appends a brand-new element on the right only). */

function starPoints(cx, cy, outer, inner, points) {
  const out = [];
  for (let i = 0; i < points * 2; i++) {
    const r = i % 2 === 0 ? outer : inner;
    const a = (Math.PI * i) / points - Math.PI / 2;
    out.push((cx + r * Math.cos(a)).toFixed(1) + ',' + (cy + r * Math.sin(a)).toFixed(1));
  }
  return out.join(' ');
}

